"""Regenerates widget/render/FontResources.kt and res/layout/widget_live_*.xml from the fonts in res/font.

Fonts are named <family>_<weight>.ttf. Each gets a RemoteViews layout (TextClock + Chronometer) so live
widget text can use the bundled typeface via android:fontFamily="@font/...".
Run from the repository root:  python tools/gen_font_resources.py
"""
import os, re, collections
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT_DIR = os.path.join(ROOT, "app/src/main/res/font")
ENUM = {"inter": "INTER", "nunito": "NUNITO", "poppins": "POPPINS", "space_grotesk": "SPACE_GROTESK",
        "playfair_display": "PLAYFAIR", "cormorant_garamond": "CORMORANT", "jetbrains_mono": "JETBRAINS_MONO",
        "orbitron": "ORBITRON", "oswald": "OSWALD", "bebas_neue": "BEBAS", "quicksand": "QUICKSAND"}
fams = collections.defaultdict(list)
for f in os.listdir(FONT_DIR):
    m = re.match(r"(.+)_(\d{3})\.ttf$", f)
    if m: fams[m.group(1)].append(int(m.group(2)))
def pick(ws, w):
    if w == "LIGHT": return min(ws)
    if w == "REGULAR": return 400 if 400 in ws else min(ws, key=lambda x: abs(x - 400))
    return max([x for x in ws if x >= 600] or [max(ws)])
out = ["package app.suncanvas.widget.render", "", "import app.suncanvas.R",
       "import app.suncanvas.widget.model.FontWeightChoice", "import app.suncanvas.widget.model.WidgetFont", "",
       "/** Generated by tools/gen_font_resources.py — maps widget fonts to bundled font files and live-clock layouts. */",
       "object FontResources {"]
for fn, kind in (("fontRes", "font"), ("liveLayout", "layout")):
    out.append(f"    fun {fn}(font: WidgetFont, weight: FontWeightChoice): Int = when (font) {{")
    for pre, e in ENUM.items():
        ws = sorted(fams[pre]); ref = (lambda w: f"R.font.{pre}_{w}") if kind == "font" else (lambda w: f"R.layout.widget_live_{pre}_{w}")
        out.append(f"        WidgetFont.{e} -> when (weight) {{ FontWeightChoice.LIGHT -> {ref(pick(ws,'LIGHT'))}; "
                   f"FontWeightChoice.REGULAR -> {ref(pick(ws,'REGULAR'))}; FontWeightChoice.BOLD -> {ref(pick(ws,'BOLD'))} }}")
    out += ["    }", ""]
out.append("}")
open(os.path.join(ROOT, "app/src/main/java/app/suncanvas/widget/render/FontResources.kt"), "w").write("\n".join(out) + "\n")
print("families:", {k: sorted(v) for k, v in fams.items()})
